function ErrorComponent({ error, reset }: { error: Error; reset: () => void }) {
  console.error(error);
  const router = useRouter();
  useEffect(() => {
    reportLovableError(error, { boundary: "tanstack_root_error_component" });
  }, [error]);

  return (
    <div className="flex min-h-screen items-center justify-center bg-background px-4">
      <div className="max-w-md text-center">
        <h1 className="text-xl font-semibold tracking-tight text-foreground">This page didn't load</h1>
        <p className="mt-2 text-sm text-muted-foreground">Something went wrong on our end.</p>
        <div className="mt-6 flex flex-wrap justify-center gap-2">
          <button
            onClick={() => { router.invalidate(); reset(); }}
            className="bg-brand-navy px-4 py-2 text-sm font-bold text-white uppercase hover:bg-brand-navy-dark"
          >Try again</button>
          <a href="/" className="border border-brand-navy px-4 py-2 text-sm font-bold text-brand-navy uppercase hover:bg-brand-navy hover:text-white">Go home</a>
        </div>
      </div>
    </div>
  );
}

